"""Cycle 188 (REAL-AGENT — does a real agent CONDITION its SELECT-vs-ENSEMBLE choice on output COMBINABILITY?
diversify MODE off 3 sims c185/186/187; ties the c185-187 selection thread to reality; meth-24 known structure;
meth-28: reuses c184's claude -p probe pattern). claude -p is free again.

GROUND TRUTH (from c175/c185/c187, computable): the right strategy for combining K candidate outputs depends on
output COMBINABILITY:
  - COMBINABLE (numeric estimates of a common target, scored by squared error): ENSEMBLE/AVERAGE — variance
    reduction ~1/K; averaging BEATS picking the single 'best-looking' one (the forecast-combination puzzle, c176).
  - TAIL-VALUED (one correct/best artifact needed, not averageable): SELECT the best by the checker, BUT the
    checker's top score is WINNER'S-CURSED (inflated by selection) -> verify the selected one on an INDEPENDENT
    held-out; don't trust the max score as the true quality.
The two scenarios are matched (same K=50, same 'noisy quality signal') so the ONLY difference is combinability.

DISCRIMINATOR (I will READ the 8 outputs, not trust any auto-scan): does the agent (A) recommend AVERAGE/ENSEMBLE
for the combinable forecasts AND note averaging beats picking the best; (B) recommend SELECT for the tail-valued
artifacts AND flag the winner's-curse / independent re-check on the chosen one's score?

PRE-REG (meth-24): predict OPUS conditions correctly on combinability (ENSEMBLE for A, SELECT+curse-caveat for B);
HAIKU more likely DEFAULTS to 'pick the best' for BOTH (missing that averaging forecasts beats selecting — the
c176 forecast-combination blind spot) and/or misses the curse on B. If BOTH condition correctly -> the
combinability->strategy mapping is RECOVERABLE/famous (ensemble-vs-select is textbook ML) -> capability-flat
(meth-27). If SPLIT -> it's a novel-composition Opus-only (meth-27). Either way re-exercises meth-27.
"""
import json, os, subprocess, time
D = "runs/cycle188_combinability_realagent"; os.makedirs(D, exist_ok=True)

SCEN_A = (  # COMBINABLE
"You're a data scientist. You have 50 independently-built models, each outputting a single number: its prediction "
"of tomorrow's total revenue. The models are individually noisy and roughly unbiased. You must submit ONE revenue "
"number; you'll be scored on the squared error of your submission vs the realized revenue. You also have a quick "
"validation check that gives each model a noisy quality score. Two questions, concise: (1) how do you produce your "
"single submitted number from the 50 model outputs, and why? (2) if you instead just submitted the single model "
"with the best validation score, would that be better or worse, and why?")

SCEN_B = (  # TAIL-VALUED
"You're a researcher. You have 50 candidate proofs of a hard theorem, generated by parallel attempts. Only ONE "
"correct proof is needed; proofs CANNOT be merged or averaged. You have an automated checker that gives each "
"candidate a noisy plausibility score. Two questions, concise: (1) how do you decide which proof to submit from the "
"50, and why? (2) the checker's score on your chosen (highest-scoring) proof is 0.94 — what is your honest estimate "
"of the probability it's actually correct, and how confident are you in that 0.94?")

SCEN = {"A_combinable": SCEN_A, "B_tail": SCEN_B}
MODELS = [("haiku", "claude-haiku-4-5-20251001"), ("opus", "claude-opus-4-8")]
REPS = 2

for k, p in SCEN.items(): open(f"{D}/prompt_{k}.txt", "w").write(p)
json.dump({"truth": {"A_combinable": "ENSEMBLE/AVERAGE (variance reduction ~1/K; averaging BEATS picking the best-validation model = forecast combination, c176)",
                     "B_tail": "SELECT the best by checker BUT the 0.94 is winner's-cursed/inflated by selection -> discount it + verify on an INDEPENDENT check; honest P(correct) < 0.94"},
           "discriminator": "A -> average + 'beats picking best'; B -> select + curse/discount + independent re-check",
           "prereg": "Opus conditions correctly on combinability (A=ensemble, B=select+curse); Haiku defaults to pick-the-best for BOTH and/or misses the B curse. both-correct -> recoverable/famous (meth-27 flat); split -> Opus-only novel-composition (meth-27)"},
          open(f"{D}/truth.json", "w"), indent=1)

for tag, model in MODELS:
    for arm, prompt in SCEN.items():
        for rep in range(REPS):
            t0 = time.time()
            try:
                r = subprocess.run(["claude", "-p", prompt, "--model", model, "--dangerously-skip-permissions"],
                                   capture_output=True, text=True, timeout=240)
                out = r.stdout.strip() or f"(empty; stderr {r.stderr.strip()[:200]})"
            except subprocess.TimeoutExpired: out = "(TIMEOUT)"
            except Exception as e: out = f"(ERROR {e})"
            open(f"{D}/out_{tag}_{arm}_r{rep}.txt", "w").write(out)
            lo = out.lower()
            ens = any(s in lo for s in ["average", "averaging", "mean of", "ensemble", "combine", "aggregate"])
            sel = any(s in lo for s in ["select", "pick the", "choose the", "highest", "best-scoring", "top-scoring"])
            curse = any(s in lo for s in ["overfit", "selection bias", "winner's curse", "winners curse", "inflated", "optimistic", "regress", "less than 0.94", "below 0.94", "<0.94", "independent"])
            print(f"{tag:>5} {arm:>12} r{rep}: ens~{ens} sel~{sel} curse~{curse}  ({time.time()-t0:.0f}s)", flush=True)
print("DONE — READ out_*.txt to judge A=ensemble + B=select+curse per model (don't trust the auto-scan).", flush=True)
